#!/usr/bin/env python3
"""Synthetic CC0 corpus. PNG/TIFF stream rows; JPEG capped at 32MP via Pillow.
Full corpus requires explicit --full --budget-mib (encoded output conservative bound).
No original/user photographs are read. Generated bytes are deterministic per tool versions.
"""
import argparse, hashlib, json, math, os, shutil, struct, subprocess, time, zlib
from pathlib import Path
from PIL import Image, ImageCms

def pixel(x,y): return (x%256,y%256,(x+y)%256,(x+y)%256)
def row_bytes(width,y,channels):
    # Build at most one row; the 256-pixel pattern is deliberately compressible.
    pattern=bytes(v for x in range(256) for v in pixel(x,y)[:channels])
    return (pattern*((width+255)//256))[:width*channels]
def write_png(path,width,height,channels=4):
    def chunk(f,kind,data):
        f.write(struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data)&0xffffffff))
    with open(path,'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n');chunk(f,b'IHDR',struct.pack('>IIBBBBB',width,height,8,{1:0,3:2,4:6}[channels],0,0,0))
        codec=zlib.compressobj(3)
        for y in range(height):
            data=codec.compress(b'\0'+row_bytes(width,y,channels))
            if data:chunk(f,b'IDAT',data)
        chunk(f,b'IDAT',codec.flush());chunk(f,b'IEND',b'')
def write_tiff(path,width,height,channels=3):
    # Baseline little-endian TIFF, one strip per row, lossless uncompressed.
    tags=[(256,4,1,width),(257,4,1,height),(258,3,channels,None),(259,3,1,1),(262,3,1,2 if channels==3 else 1),(273,4,height,None),(277,3,1,channels),(278,4,1,1),(279,4,height,None),(284,3,1,1)]
    offset=8+2+12*len(tags)+4; extras=bytearray()
    def add(data):
        nonlocal offset
        at=offset;extras.extend(data);offset+=len(data);return at
    bits=8 if channels==1 else add(struct.pack('<'+'H'*channels,*([8]*channels)))
    offsets_at=offset; add(bytes(height*4));counts_at=add(struct.pack('<'+'I'*height,*([width*channels]*height)))
    pixels_at=offset
    strip_offsets=struct.pack('<'+'I'*height,*[pixels_at+y*width*channels for y in range(height)])
    extras[offsets_at-(8+2+12*len(tags)+4):offsets_at-(8+2+12*len(tags)+4)+height*4]=strip_offsets
    values={258:bits,273:offsets_at,279:counts_at}
    with open(path,'wb') as f:
        f.write(b'II'+struct.pack('<HIH',42,8,len(tags)))
        for tag,kind,count,value in tags:f.write(struct.pack('<HHII',tag,kind,count,values.get(tag,value)))
        f.write(struct.pack('<I',0));f.write(extras)
        for y in range(height):f.write(row_bytes(width,y,channels))
def metadata(path):
    with Image.open(path) as im:
        return dict(width=im.width,height=im.height,depth=16 if '16' in im.mode else 8,mode=im.mode,format=im.format,icc=bool(im.info.get('icc_profile')),orientation=im.getexif().get(274,1),encoding=('progressive' if im.info.get('progressive') else 'baseline') if im.format=='JPEG' else ('tiled' if im.format=='TIFF' and  tiled(im) else 'striped' if im.format=='TIFF' else 'deflate'))
def tiled(im):return 322 in im.tag_v2

