import { fireEvent, render, screen } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { EditorProvider } from '../state/editor'
import { Inspector } from './Inspector'

beforeEach(()=>localStorage.removeItem('draivio-inspector-layout-v1'))
const rect = (top:number,height=300) => ({left:0,right:320,top,bottom:top+height,width:320,height,x:0,y:top,toJSON(){}})
function setup(){
 render(<EditorProvider><Inspector inspectorWidth={320} onResizeStart={vi.fn()} onResizeBy={vi.fn()}/></EditorProvider>)
 Object.defineProperty(document,'elementFromPoint',{configurable:true,value:vi.fn().mockReturnValue(null)})
}
function groups(){return Array.from(document.querySelectorAll<HTMLElement>('.dock-group'))}
function drag(name:string,index:number,offset:number,pointer=false){
 groups().forEach((group,i)=>vi.spyOn(group,'getBoundingClientRect').mockReturnValue(rect(i*307)))
 const button=screen.getByRole('button',{name})
 if(pointer){
  fireEvent.pointerDown(button,{button:0,pointerId:7,pointerType:'pen',clientX:10,clientY:10})
  fireEvent.pointerMove(document,{pointerId:7,clientX:160,clientY:index*307+offset})
  fireEvent.pointerUp(document,{pointerId:7,clientX:160,clientY:index*307+offset})
 }else{
  fireEvent.mouseDown(button,{button:0,clientX:10,clientY:10})
  fireEvent.mouseMove(document,{clientX:160,clientY:index*307+offset})
  fireEvent.mouseUp(document,{clientX:160,clientY:index*307+offset})
 }
 // Native pointer sequence generates a trailing click, which must be ignored.
 fireEvent.click(screen.getByRole('button',{name}))
}

describe('composable inspector panels',()=>{
 it('splits, reorders and merges into any panel group using mouse and pen',()=>{
  setup()
  drag('属性',0,290)
  expect(groups().map(g=>g.getAttribute('aria-label'))).toEqual(['图层 / AI 结果面板组','属性面板组'])
  drag('图层',1,290,true)
  expect(groups().map(g=>g.getAttribute('aria-label'))).toEqual(['AI 结果面板组','属性面板组','图层面板组'])
  drag('图层',1,150)
  expect(groups().map(g=>g.getAttribute('aria-label'))).toEqual(['AI 结果面板组','属性 / 图层面板组'])
  drag('AI 结果',1,150)
  expect(groups()).toHaveLength(1)
  expect(groups()[0]).toHaveAttribute('aria-label','属性 / 图层 / AI 结果面板组')
  expect(Number(groups()[0].style.flexGrow)).toBe(1)
  expect(screen.getByRole('button',{name:'AI 结果'})).toHaveAttribute('aria-expanded','true')
  expect(screen.getAllByRole('button',{name:'图层'})).toHaveLength(1)
 })
 it('resizes adjacent groups, clamps sizes and supports keyboard resizing',()=>{
  setup();drag('属性',0,290)
  groups().forEach((group,i)=>vi.spyOn(group,'getBoundingClientRect').mockReturnValue(rect(i*307)))
  const divider=screen.getByRole('separator',{name:'调整图层与属性面板高度'})
  const before=groups().map(g=>Number(g.style.flexGrow))
  fireEvent.pointerDown(divider,{button:0,pointerId:1,clientY:300})
  fireEvent.pointerMove(document,{pointerId:1,clientY:350})
  fireEvent.pointerUp(document,{pointerId:1,clientY:350})
  expect(Number(groups()[0].style.flexGrow)).toBeGreaterThan(before[0])
  expect(Number(groups()[1].style.flexGrow)).toBeLessThan(before[1])
  fireEvent.keyDown(divider,{key:'ArrowUp'})
  expect(Number(groups()[0].style.flexGrow)).toBeLessThan(.5*350/300)
  fireEvent.mouseDown(divider,{button:0,clientY:300})
  fireEvent.mouseMove(document,{clientY:-10000})
  fireEvent.mouseUp(document,{clientY:-10000})
  expect(Number(groups()[0].style.flexGrow)).toBeGreaterThan(0)
  expect(Number(groups()[1].style.flexGrow)).toBeGreaterThan(0)
 })
 it.each(['图层','属性','AI 结果'])('collapses and expands %s without duplicate titles',name=>{
  setup()
  const button=screen.getByRole('button',{name})
  if(button.getAttribute('aria-selected')!=='true')fireEvent.click(button)
  expect(button).toHaveAttribute('aria-expanded','true')
  fireEvent.click(button);expect(button).toHaveAttribute('aria-expanded','false')
  fireEvent.click(button);expect(button).toHaveAttribute('aria-expanded','true')
 })
 it('retains live panel content and persists regrouping and heights',()=>{
  setup()
  // Search is real LayersPanel local state. It must survive moving its portal host.
  fireEvent.click(screen.getByRole('button',{name:'搜索与筛选图层'}))
  const search=screen.getByRole('searchbox',{name:'搜索图层'})
  fireEvent.change(search,{target:{value:'春日'}})
  drag('图层',0,290)
  expect(screen.getByRole('searchbox',{name:'搜索图层'})).toBe(search)
  expect(search).toHaveValue('春日')
  const saved=JSON.parse(localStorage.getItem('draivio-inspector-layout-v1')!)
  expect(saved.map((g:{tabs:string[]})=>g.tabs)).toEqual([['edit','results'],['layers']])
 })
 it('previews placement and cancels on Escape, blur and pointercancel',()=>{
  setup();groups().forEach(g=>vi.spyOn(g,'getBoundingClientRect').mockReturnValue(rect(0)))
  const button=screen.getByRole('button',{name:'属性'})
  fireEvent.mouseDown(button,{button:0,clientX:10,clientY:10})
  fireEvent.mouseMove(document,{clientX:12,clientY:12})
  expect(screen.queryByTestId('inspector-drag-preview')).not.toBeInTheDocument()
  fireEvent.mouseMove(document,{clientX:80,clientY:150})
  const preview=screen.getByTestId('inspector-drag-preview')
  expect(preview.parentElement).toBe(document.body)
  expect(preview.style.left).toBe('96px')
  expect(screen.getByText('合并为标签组')).toBeInTheDocument()
  fireEvent.keyDown(document,{key:'Escape'})
  expect(screen.queryByTestId('inspector-drag-preview')).not.toBeInTheDocument()
  fireEvent.pointerDown(button,{button:0,pointerId:3,clientX:10,clientY:10})
  fireEvent.pointerMove(document,{pointerId:3,clientX:80,clientY:290})
  fireEvent.pointerCancel(document,{pointerId:3,clientX:80,clientY:290})
  expect(groups()).toHaveLength(1)
  expect(screen.queryByTestId('inspector-drag-preview')).not.toBeInTheDocument()
  fireEvent.mouseDown(button,{button:0,clientX:10,clientY:10})
  fireEvent.mouseMove(document,{clientX:80,clientY:290})
  fireEvent.blur(window)
  expect(screen.queryByTestId('inspector-drag-preview')).not.toBeInTheDocument()
 })
})

it('collapses through the unified tab without keeping a duplicate content title',()=>{
 setup()
 expect(screen.queryByRole('heading',{name:'图层'})).not.toBeInTheDocument()
 fireEvent.click(screen.getByRole('button',{name:'图层'}))
 expect(screen.getByRole('button',{name:'图层'})).toHaveAttribute('aria-expanded','false')
 fireEvent.click(screen.getByRole('button',{name:'图层'}))
 expect(screen.getByRole('button',{name:'图层'})).toHaveAttribute('aria-expanded','true')
})

it('uses one header for tabs and active panel actions, preserving state across switching',()=>{
 setup()
 const layerTab=screen.getByRole('button',{name:'图层'})
 const header=layerTab.closest('.dock-header')
 expect(header).not.toBeNull()
 expect(screen.queryByRole('heading',{name:'图层'})).not.toBeInTheDocument()
 expect(header).toContainElement(screen.getByRole('button',{name:'搜索与筛选图层'}))
 fireEvent.click(screen.getByRole('button',{name:'搜索与筛选图层'}))
 fireEvent.change(screen.getByRole('searchbox',{name:'搜索图层'}),{target:{value:'春日'}})
 fireEvent.click(screen.getByRole('button',{name:'属性'}))
 expect(screen.queryByRole('heading',{name:'属性'})).not.toBeInTheDocument()
 expect(screen.queryByRole('button',{name:'搜索与筛选图层'})).not.toBeInTheDocument()
 expect(screen.queryByText('智能滤镜 · 0')).not.toBeInTheDocument()
 expect(screen.queryByText('效果 · 未启用')).not.toBeInTheDocument()
 fireEvent.click(layerTab)
 expect(screen.getByRole('searchbox',{name:'搜索图层'})).toHaveValue('春日')
 expect(screen.getByRole('button',{name:'搜索与筛选图层'}).closest('.dock-header')).toBe(header)
})

it('does not drag or collapse a panel when using its header actions',()=>{
 setup()
 const button=screen.getByRole('button',{name:'搜索与筛选图层'})
 fireEvent.mouseDown(button,{button:0,clientX:280,clientY:12})
 fireEvent.mouseMove(document,{clientX:180,clientY:200})
 fireEvent.mouseUp(document,{clientX:180,clientY:200})
 fireEvent.click(button)
 expect(screen.queryByTestId('inspector-drag-preview')).not.toBeInTheDocument()
 expect(groups()).toHaveLength(1)
 expect(screen.getByRole('button',{name:'图层'})).toHaveAttribute('aria-expanded','true')
 expect(screen.getByRole('searchbox',{name:'搜索图层'})).toBeVisible()
})

it('reveals a collapsed panel when its header action is used and drags from header whitespace',()=>{
 setup()
 const tab=screen.getByRole('button',{name:'图层'})
 fireEvent.click(tab);expect(tab).toHaveAttribute('aria-expanded','false')
 fireEvent.click(screen.getByRole('button',{name:'搜索与筛选图层'}))
 expect(tab).toHaveAttribute('aria-expanded','true')
 expect(screen.getByRole('searchbox',{name:'搜索图层'})).toBeVisible()
 expect(screen.getByRole('searchbox',{name:'搜索图层'})).toHaveFocus()
 const input=screen.getByRole('searchbox',{name:'搜索图层'})
 fireEvent.change(input,{target:{value:'春日'}})
 groups().forEach(g=>vi.spyOn(g,'getBoundingClientRect').mockReturnValue(rect(0)))
 fireEvent.mouseDown(screen.getByText('画板 1'),{button:0,clientX:200,clientY:15})
 fireEvent.mouseMove(document,{clientX:120,clientY:290})
 expect(screen.getByTestId('inspector-drag-preview')).toBeInTheDocument()
 fireEvent.mouseUp(document,{clientX:120,clientY:290})
 expect(groups()).toHaveLength(2)
 expect(screen.getByRole('searchbox',{name:'搜索图层'})).toBe(input)
 expect(input).toHaveValue('春日')
})
