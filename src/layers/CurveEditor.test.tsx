import { fireEvent, render, screen } from '@testing-library/react'
import { expect, it, vi } from 'vitest'
import { CurveEditor } from './CurveEditor'
import { defaultCurves } from '../adjustments/curves'
import { defaultLevels } from '../adjustments/levels'
it('edits only the selected point and exposes compact levels in a separate tab', () => {
 const onCurves=vi.fn(), onLevels=vi.fn(); render(<CurveEditor curves={defaultCurves()} levels={defaultLevels()} onCurves={onCurves} onLevels={onLevels}/>)
 expect(screen.getAllByLabelText('曲线输出')).toHaveLength(1)
 fireEvent.change(screen.getByLabelText('曲线输出'),{target:{value:'64'}})
 expect(onCurves).toHaveBeenCalledWith(expect.objectContaining({rgb:[{x:0,y:64/255},{x:1,y:1}]}))
 fireEvent.click(screen.getByRole('tab',{name:'色阶'}))
 expect(screen.getByRole('tabpanel',{name:'色阶'})).toBeVisible()
 fireEvent.change(screen.getByLabelText('色阶黑场'),{target:{value:'26'}})
 expect(onLevels).toHaveBeenCalledWith({...defaultLevels(),inputBlack:26/255})
})
it('keeps draft changes outside document while preview is disabled, then applies them when enabled', () => {
 const onCurves=vi.fn(),onLevels=vi.fn();render(<CurveEditor curves={defaultCurves()} levels={defaultLevels()} onCurves={onCurves} onLevels={onLevels}/>)
 fireEvent.click(screen.getByLabelText('预览曲线'))
 fireEvent.change(screen.getByLabelText('曲线输出'),{target:{value:'51'}})
 fireEvent.click(screen.getByRole('tab',{name:'色阶'}))
 fireEvent.change(screen.getByLabelText('色阶中间调'),{target:{value:'2'}})
 expect(onCurves).not.toHaveBeenCalled();expect(onLevels).not.toHaveBeenCalled()
 fireEvent.click(screen.getByLabelText('预览曲线'))
 expect(onCurves).toHaveBeenCalledWith(expect.objectContaining({rgb:[{x:0,y:.2},{x:1,y:1}]}))
 expect(onLevels).toHaveBeenCalledWith({...defaultLevels(),gamma:2})
})
it('adds ordered distinct anchors, changes channels, renders a histogram and applies a preset',()=>{
 const onCurves=vi.fn(),onLevels=vi.fn();render(<CurveEditor curves={defaultCurves()} levels={defaultLevels()} histogram={[0,4,2]} onCurves={onCurves} onLevels={onLevels}/>)
 fireEvent.click(screen.getByRole('button',{name:'添加锚点'}));fireEvent.click(screen.getByRole('button',{name:'添加锚点'}))
 const c=onCurves.mock.calls.at(-1)![0];expect(c.rgb.map((p:any)=>p.x)).toEqual([0,.25,.5,1])
 expect(screen.getByLabelText('曲线直方图背景').querySelectorAll('rect')).toHaveLength(3)
 fireEvent.click(screen.getByRole('button',{name:'提亮预设'}));expect(onCurves.mock.calls.at(-1)![0].rgb[1]).toEqual({x:.5,y:.65})
 fireEvent.change(screen.getByLabelText('曲线通道'),{target:{value:'r'}})
 expect(screen.getByLabelText('曲线输入')).toHaveValue(0)
 fireEvent.change(screen.getByLabelText('曲线输出'),{target:{value:'20'}})
 expect(onCurves.mock.calls.at(-1)![0].r[0].y).toBeCloseTo(20/255)
})
it('previews pointer motion externally but commits only on release, and clears on cancellation',()=>{
 const onCurves=vi.fn(),onDraftCurves=vi.fn()
 render(<CurveEditor curves={defaultCurves()} levels={defaultLevels()} onCurves={onCurves} onLevels={vi.fn()} onDraftCurves={onDraftCurves}/>)
 const graph=screen.getByRole('group',{name:'曲线编辑区域'})
 vi.spyOn(graph,'getBoundingClientRect').mockReturnValue({left:0,top:0,width:256,height:256,right:256,bottom:256,x:0,y:0,toJSON(){}})
 fireEvent.pointerDown(graph,{button:0,pointerId:1,clientX:128,clientY:128})
 fireEvent.pointerMove(graph,{pointerId:1,clientX:128,clientY:80})
 expect(onDraftCurves.mock.calls.at(-1)![0].rgb[1].y).toBeGreaterThan(.5)
 expect(onCurves).not.toHaveBeenCalled()
 fireEvent.pointerUp(graph,{pointerId:1})
 expect(onCurves).toHaveBeenCalledTimes(1)
 expect(onDraftCurves.mock.calls.at(-1)![0]).toBeNull()
 fireEvent.pointerDown(graph,{button:0,pointerId:2,clientX:128,clientY:80})
 fireEvent.pointerMove(graph,{pointerId:2,clientX:120,clientY:120})
 fireEvent.keyDown(graph,{key:'Escape'})
 expect(onCurves).toHaveBeenCalledTimes(1)
 expect(onDraftCurves.mock.calls.at(-1)![0]).toBeNull()
})
it('drags input and output level handles with live values and commits once',()=>{
 const onLevels=vi.fn(),onDraftLevels=vi.fn()
 render(<CurveEditor curves={defaultCurves()} levels={defaultLevels()} onCurves={vi.fn()} onLevels={onLevels} onDraftLevels={onDraftLevels}/>)
 fireEvent.click(screen.getByRole('tab',{name:'色阶'}))
 const rail=screen.getByTestId('input-levels-rail')
 vi.spyOn(rail,'getBoundingClientRect').mockReturnValue({left:0,top:0,width:255,height:20,right:255,bottom:20,x:0,y:0,toJSON(){}})
 const black=screen.getByRole('slider',{name:'输入黑场滑块'})
 fireEvent.pointerDown(black,{button:0,pointerId:1,clientX:0})
 fireEvent.pointerMove(rail,{pointerId:1,clientX:32})
 expect(screen.getByLabelText('色阶黑场')).toHaveValue(32)
 expect(onDraftLevels.mock.calls.at(-1)![0].inputBlack).toBeCloseTo(32/255)
 expect(onLevels).not.toHaveBeenCalled()
 fireEvent.pointerUp(rail,{pointerId:1})
 expect(onLevels).toHaveBeenCalledTimes(1);expect(onDraftLevels.mock.calls.at(-1)![0]).toBeNull()
 const out=screen.getByTestId('output-levels-rail')
 vi.spyOn(out,'getBoundingClientRect').mockReturnValue({left:0,top:0,width:255,height:20,right:255,bottom:20,x:0,y:0,toJSON(){}})
 fireEvent.pointerDown(screen.getByRole('slider',{name:'输出白场滑块'}),{button:0,pointerId:2,clientX:255})
 fireEvent.pointerMove(out,{pointerId:2,clientX:220});fireEvent.pointerUp(out,{pointerId:2})
 expect(screen.getByLabelText('输出白场')).toHaveValue(220);expect(onLevels).toHaveBeenCalledTimes(2)
})
