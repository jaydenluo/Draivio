 const onLevels=vi.fn(),onDraftLevels=vi.fn()
 render(<CurveEditor curves={defaultCurves()} levels={defaultLevels()} onCurves={vi.fn()} onLevels={onLevels} onDraftLevels={onDraftLevels}/>)
